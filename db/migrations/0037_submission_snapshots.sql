BEGIN;
CREATE TABLE verivaro_private.submission_snapshots(
 submission_id uuid PRIMARY KEY,tenant_id uuid NOT NULL,project_id uuid NOT NULL,preparer_id uuid NOT NULL,session_id uuid NOT NULL,
 preparer_generation uuid[] NOT NULL CHECK(cardinality(preparer_generation)=3 AND array_position(preparer_generation,NULL) IS NULL),
 manifest text NOT NULL CHECK(octet_length(manifest) BETWEEN 1 AND 2097152),
 sha256 text NOT NULL CHECK(sha256~'^[a-f0-9]{64}$'),created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 FOREIGN KEY(tenant_id,project_id) REFERENCES verivaro.projects(tenant_id,id)
);
CREATE TABLE verivaro_private.submission_reviews(
 submission_id uuid PRIMARY KEY REFERENCES verivaro_private.submission_snapshots(submission_id),
 reviewer_id uuid NOT NULL,session_id uuid NOT NULL,reviewer_generation uuid[] NOT NULL CHECK(cardinality(reviewer_generation)=3 AND array_position(reviewer_generation,NULL) IS NULL),
 decision text NOT NULL CHECK(decision IN ('approved','rejected')),reason text NOT NULL CHECK(char_length(reason) BETWEEN 1 AND 512 AND octet_length(reason)<=2048),
 reviewed_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE verivaro_private.submission_authorizations(
 submission_id uuid PRIMARY KEY REFERENCES verivaro_private.submission_reviews(submission_id),owner_id uuid NOT NULL,session_id uuid NOT NULL,
 owner_generation uuid[] NOT NULL CHECK(cardinality(owner_generation)=3 AND array_position(owner_generation,NULL) IS NULL),
 authorized_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
REVOKE ALL ON verivaro_private.submission_snapshots,verivaro_private.submission_reviews,verivaro_private.submission_authorizations FROM PUBLIC;
CREATE TRIGGER submission_snapshot_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON verivaro_private.submission_snapshots FOR EACH STATEMENT EXECUTE FUNCTION verivaro_private.identity_event_immutable();
CREATE TRIGGER submission_review_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON verivaro_private.submission_reviews FOR EACH STATEMENT EXECUTE FUNCTION verivaro_private.identity_event_immutable();
CREATE TRIGGER submission_authorization_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON verivaro_private.submission_authorizations FOR EACH STATEMENT EXECUTE FUNCTION verivaro_private.identity_event_immutable();
CREATE TRIGGER archive_submission_guard BEFORE INSERT ON verivaro_private.submission_snapshots FOR EACH ROW EXECUTE FUNCTION verivaro_private.guard_project_write();

-- Caller holds graph_actor's project lock. Canonical PostgreSQL JSONB text
-- is stored verbatim, not regenerated by the download client. No UI hints,
-- evaluation timestamps or actor-specific flags enter the content digest.
CREATE FUNCTION verivaro_private.submission_manifest(t uuid,p uuid) RETURNS text
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,verivaro_private AS $manifest$
DECLARE g jsonb;rules jsonb;objects jsonb;q verivaro.projects%ROWTYPE;outcome text;n integer;total bigint;
BEGIN
 g:=verivaro_verification.assessment(t,p);
 IF g->>'archived'='true' OR g->'summary'->>'status'<>'criteria_satisfied' OR EXISTS(
 SELECT 1 FROM jsonb_array_elements(g->'requirements') x WHERE x->>'state' NOT IN ('satisfied','not_applicable'))
 THEN RAISE EXCEPTION 'submission blocked' USING ERRCODE='23505';END IF;
 SELECT * INTO q FROM verivaro.projects WHERE tenant_id=t AND id=p;
 SELECT jsonb_agg((x-'canRevise'-'canReview'-'canLink'-'links')||jsonb_build_object('links',
 COALESCE((SELECT jsonb_agg(l-'canReview' ORDER BY l->>'linkId') FROM jsonb_array_elements(x->'links') l),'[]'::jsonb)) ORDER BY x->>'requirementId')
 INTO rules FROM jsonb_array_elements(g->'requirements') x;
 WITH ids AS (
 SELECT (l->>'evidenceId')::uuid AS id FROM jsonb_array_elements(rules) x CROSS JOIN LATERAL jsonb_array_elements(x->'links') l
 UNION SELECT (x->'source'->>'evidenceId')::uuid FROM jsonb_array_elements(rules) x WHERE x->'source'->>'evidenceId' IS NOT NULL
 )
 SELECT count(*)::integer,COALESCE(sum(o.bytes),0),COALESCE(jsonb_agg(jsonb_build_object('id',o.evidence_id,'sha256',o.sha256,'bytes',o.bytes,'mediaType',o.media_type) ORDER BY o.evidence_id),'[]'::jsonb)
 INTO n,total,objects FROM ids JOIN verivaro_private.evidence_objects o ON o.evidence_id=ids.id AND o.tenant_id=t AND o.project_id=p;
 IF n<1 OR n>64 OR total>16777216 THEN RAISE EXCEPTION 'submission capacity' USING ERRCODE='54000';END IF;
 outcome:=jsonb_build_object('version',1,'tenantId',t,'projectId',p,'projectRevision',q.revision,'projectName',q.name,'summary',g->'summary','requirements',rules,'evidence',objects,
 'scope','reviewed subset only; internal authorization is not recipient acceptance, external delivery or certification')::text;
 IF octet_length(outcome)>2097152 THEN RAISE EXCEPTION 'submission capacity' USING ERRCODE='54000';END IF;
 RETURN outcome;
END $manifest$;
REVOKE ALL ON FUNCTION verivaro_private.submission_manifest(uuid,uuid) FROM PUBLIC;
CREATE FUNCTION verivaro_verification.prepare_submission(t uuid,p uuid,s uuid) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,verivaro_private AS $prepare$
DECLARE c text[];m text;h text;prior verivaro_private.submission_snapshots%ROWTYPE;g uuid[];
BEGIN
 c:=verivaro_private.graph_actor(t,p,'submitter');g:=verivaro_private.release_generation(t,p,c[2]::uuid,'submitter');
 IF s IS NULL THEN RAISE EXCEPTION 'submission denied' USING ERRCODE='42501';END IF;
 m:=verivaro_private.submission_manifest(t,p);h:=encode(verivaro_private.digest(convert_to(m,'UTF8'),'sha256'),'hex');
 SELECT * INTO prior FROM verivaro_private.submission_snapshots WHERE submission_id=s;
 IF FOUND THEN
 IF prior.tenant_id<>t OR prior.project_id<>p OR prior.preparer_id<>c[2]::uuid OR prior.sha256<>h OR prior.preparer_generation IS DISTINCT FROM g THEN RAISE EXCEPTION 'submission conflict' USING ERRCODE='23505';END IF;
 ELSE
 PERFORM pg_advisory_xact_lock(740129816158::bigint);
 IF (SELECT count(*) FROM verivaro_private.submission_snapshots)>=1024 OR (SELECT count(*) FROM verivaro_private.submission_snapshots WHERE tenant_id=t AND project_id=p)>=16
 OR (SELECT COALESCE(sum(octet_length(manifest)),0) FROM verivaro_private.submission_snapshots)+octet_length(m)>67108864 THEN RAISE EXCEPTION 'submission capacity' USING ERRCODE='54000';END IF;
 INSERT INTO verivaro_private.submission_snapshots(submission_id,tenant_id,project_id,preparer_id,session_id,preparer_generation,manifest,sha256) VALUES(s,t,p,c[2]::uuid,c[3]::uuid,g,m,h);
 END IF;
 RETURN jsonb_build_object('submissionId',s,'sha256',h);
END $prepare$;
CREATE FUNCTION verivaro_private.current_submission(t uuid,p uuid,s uuid,h text) RETURNS verivaro_private.submission_snapshots
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,verivaro_private AS $current$
DECLARE q verivaro_private.submission_snapshots%ROWTYPE;
BEGIN
 SELECT * INTO q FROM verivaro_private.submission_snapshots WHERE submission_id=s AND tenant_id=t AND project_id=p;
 IF NOT FOUND OR q.sha256 IS DISTINCT FROM h THEN RAISE EXCEPTION 'submission denied' USING ERRCODE='42501';END IF;
 IF q.created_at<clock_timestamp()-interval '7 days' OR q.preparer_generation IS DISTINCT FROM verivaro_private.release_generation(t,p,q.preparer_id,'submitter')
 OR q.manifest IS DISTINCT FROM verivaro_private.submission_manifest(t,p) OR encode(verivaro_private.digest(convert_to(q.manifest,'UTF8'),'sha256'),'hex')<>h
 THEN RAISE EXCEPTION 'stale submission' USING ERRCODE='23505';END IF;
 RETURN q;
END $current$;
REVOKE ALL ON FUNCTION verivaro_private.current_submission(uuid,uuid,uuid,text) FROM PUBLIC;
CREATE FUNCTION verivaro_verification.review_submission(t uuid,p uuid,s uuid,h text,d text,why text) RETURNS boolean
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,verivaro_private AS $review$
DECLARE c text[];q verivaro_private.submission_snapshots%ROWTYPE;v verivaro_private.submission_reviews%ROWTYPE;g uuid[];
BEGIN
 c:=verivaro_private.graph_actor(t,p,'reviewer');q:=verivaro_private.current_submission(t,p,s,h);g:=verivaro_private.release_generation(t,p,c[2]::uuid,'reviewer');
 IF q.preparer_id=c[2]::uuid OR d IS NULL OR d NOT IN ('approved','rejected') OR why IS NULL OR char_length(why) NOT BETWEEN 1 AND 512 OR octet_length(why)>2048 OR why<>btrim(why) OR why~'[[:cntrl:]]' THEN RAISE EXCEPTION 'submission review denied' USING ERRCODE='42501';END IF;
 SELECT * INTO v FROM verivaro_private.submission_reviews WHERE submission_id=s;
 IF FOUND THEN
 IF v.reviewer_id<>c[2]::uuid OR v.decision<>d OR v.reason<>why OR v.reviewer_generation IS DISTINCT FROM g THEN RAISE EXCEPTION 'submission conflict' USING ERRCODE='23505';END IF;
 ELSE INSERT INTO verivaro_private.submission_reviews(submission_id,reviewer_id,session_id,reviewer_generation,decision,reason) VALUES(s,c[2]::uuid,c[3]::uuid,g,d,why);END IF;
 RETURN true;
END $review$;
CREATE FUNCTION verivaro_private.submission_approved(t uuid,p uuid,s uuid,h text) RETURNS verivaro_private.submission_snapshots
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,verivaro_private AS $approved$
DECLARE q verivaro_private.submission_snapshots%ROWTYPE;v verivaro_private.submission_reviews%ROWTYPE;c text[];
BEGIN
 c:=verivaro_private.graph_actor(t,p,'owner');q:=verivaro_private.current_submission(t,p,s,h);
 SELECT * INTO v FROM verivaro_private.submission_reviews WHERE submission_id=s;
 IF NOT FOUND OR v.decision<>'approved' OR c[2]::uuid IN(q.preparer_id,v.reviewer_id) OR v.reviewer_id=q.preparer_id
 OR v.reviewed_at<clock_timestamp()-interval '24 hours' OR v.reviewer_generation IS DISTINCT FROM verivaro_private.release_generation(t,p,v.reviewer_id,'reviewer')
 THEN RAISE EXCEPTION 'submission approval denied' USING ERRCODE='42501';END IF;
 RETURN q;
END $approved$;
REVOKE ALL ON FUNCTION verivaro_private.submission_approved(uuid,uuid,uuid,text) FROM PUBLIC;
CREATE FUNCTION verivaro_verification.authorize_submission(t uuid,p uuid,s uuid,h text) RETURNS boolean
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,verivaro_private AS $authorize$
DECLARE q verivaro_private.submission_snapshots%ROWTYPE;c text[];v verivaro_private.submission_authorizations%ROWTYPE;g uuid[];
BEGIN
 q:=verivaro_private.submission_approved(t,p,s,h);c:=verivaro.bound_context();g:=verivaro_private.release_generation(t,p,c[2]::uuid,'owner');
 SELECT * INTO v FROM verivaro_private.submission_authorizations WHERE submission_id=s;
 IF FOUND THEN
 IF v.owner_id<>c[2]::uuid OR v.owner_generation IS DISTINCT FROM g THEN RAISE EXCEPTION 'submission conflict' USING ERRCODE='23505';END IF;
 ELSE INSERT INTO verivaro_private.submission_authorizations(submission_id,owner_id,session_id,owner_generation) VALUES(s,c[2]::uuid,c[3]::uuid,g);END IF;
 RETURN true;
END $authorize$;
CREATE FUNCTION verivaro_verification.read_submission(t uuid,p uuid,s uuid,h text) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,verivaro_private AS $read$
DECLARE q verivaro_private.submission_snapshots%ROWTYPE;c text[];v verivaro_private.submission_authorizations%ROWTYPE;rv verivaro_private.submission_reviews%ROWTYPE;
BEGIN
 q:=verivaro_private.submission_approved(t,p,s,h);c:=verivaro.bound_context();
 SELECT * INTO v FROM verivaro_private.submission_authorizations WHERE submission_id=s;
 IF NOT FOUND OR v.owner_id<>c[2]::uuid OR v.owner_generation IS DISTINCT FROM verivaro_private.release_generation(t,p,c[2]::uuid,'owner') OR v.authorized_at<clock_timestamp()-interval '1 hour' THEN RAISE EXCEPTION 'submission download denied' USING ERRCODE='42501';END IF;
 SELECT * INTO rv FROM verivaro_private.submission_reviews WHERE submission_id=s;
 RETURN jsonb_build_object('submissionId',s,'sha256',h,'manifest',q.manifest,'preparedAt',q.created_at,'reviewedAt',rv.reviewed_at,'authorizedAt',v.authorized_at,'reviewReason',rv.reason,'authorization','internal owner-authorized download only');
END $read$;
-- Scoped historical metadata, no cross-project lookup by identifier alone.
CREATE FUNCTION verivaro_verification.submission_list(t uuid,p uuid) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=pg_catalog,verivaro_private AS $list$
DECLARE c text[];tr text;pr text;closed boolean;
BEGIN
 c:=verivaro.bound_context();
 IF c IS NULL OR c[1]<>t::text OR NOT verivaro.active_identity() THEN RAISE EXCEPTION 'submission denied' USING ERRCODE='42501';END IF;
 SELECT m.role,pm.role,q.archived_at IS NOT NULL INTO tr,pr,closed FROM verivaro.memberships m JOIN verivaro.project_members pm ON pm.tenant_id=m.tenant_id AND pm.actor_id=m.actor_id JOIN verivaro.projects q ON q.tenant_id=pm.tenant_id AND q.id=pm.project_id
 WHERE m.tenant_id=t AND m.actor_id=c[2]::uuid AND m.revoked_at IS NULL AND pm.project_id=p AND pm.revoked_at IS NULL AND (pm.expires_at IS NULL OR pm.expires_at>statement_timestamp());
 IF NOT FOUND THEN RAISE EXCEPTION 'submission denied' USING ERRCODE='42501';END IF;
 RETURN COALESCE((SELECT jsonb_agg(jsonb_build_object('id',s.submission_id,'sha256',s.sha256,'createdAt',s.created_at,'decision',v.decision,'reason',v.reason,'authorizedAt',z.authorized_at,
 'canReview',NOT closed AND tr='reviewer' AND pr='reviewer' AND s.preparer_id<>c[2]::uuid AND v.submission_id IS NULL,
 'canAuthorize',NOT closed AND tr='owner' AND pr='owner' AND s.preparer_id<>c[2]::uuid AND v.reviewer_id<>c[2]::uuid AND v.decision='approved' AND z.submission_id IS NULL,
 'canDownload',NOT closed AND tr='owner' AND pr='owner' AND z.owner_id=c[2]::uuid AND z.authorized_at>=statement_timestamp()-interval '1 hour') ORDER BY s.created_at DESC,s.submission_id)
 FROM verivaro_private.submission_snapshots s LEFT JOIN verivaro_private.submission_reviews v USING(submission_id) LEFT JOIN verivaro_private.submission_authorizations z USING(submission_id)
 WHERE s.tenant_id=t AND s.project_id=p AND (s.preparer_id=c[2]::uuid OR (tr='owner' AND pr='owner') OR (tr='reviewer' AND pr='reviewer'))),'[]'::jsonb);
END $list$;
CREATE FUNCTION verivaro_verification.inspect_submission(t uuid,p uuid,s uuid) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=pg_catalog,verivaro_private AS $inspect$
DECLARE listing jsonb;q verivaro_private.submission_snapshots%ROWTYPE;
BEGIN
 listing:=verivaro_verification.submission_list(t,p);
 IF NOT EXISTS(SELECT 1 FROM jsonb_array_elements(listing) x WHERE x->>'id'=s::text) THEN RAISE EXCEPTION 'submission denied' USING ERRCODE='42501';END IF;
 SELECT * INTO q FROM verivaro_private.submission_snapshots WHERE submission_id=s AND tenant_id=t AND project_id=p;
 IF NOT FOUND OR encode(verivaro_private.digest(convert_to(q.manifest,'UTF8'),'sha256'),'hex')<>q.sha256 THEN RAISE EXCEPTION 'submission denied' USING ERRCODE='42501';END IF;
 RETURN jsonb_build_object('submissionId',s,'sha256',q.sha256,'manifest',q.manifest);
END $inspect$;
REVOKE ALL ON FUNCTION verivaro_verification.prepare_submission(uuid,uuid,uuid),verivaro_verification.review_submission(uuid,uuid,uuid,text,text,text),verivaro_verification.authorize_submission(uuid,uuid,uuid,text),verivaro_verification.read_submission(uuid,uuid,uuid,text),verivaro_verification.submission_list(uuid,uuid),verivaro_verification.inspect_submission(uuid,uuid,uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION verivaro_verification.prepare_submission(uuid,uuid,uuid),verivaro_verification.review_submission(uuid,uuid,uuid,text,text,text),verivaro_verification.authorize_submission(uuid,uuid,uuid,text),verivaro_verification.read_submission(uuid,uuid,uuid,text),verivaro_verification.submission_list(uuid,uuid),verivaro_verification.inspect_submission(uuid,uuid,uuid) TO verivaro_runtime;
COMMIT;
